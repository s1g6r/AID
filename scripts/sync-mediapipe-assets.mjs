/**
 * Puts the MediaPipe assets where the browser can fetch them, at paths that
 * change whenever the bytes change.
 *
 * Both assets are served from our own origin rather than a CDN: no third-party
 * request happens while a camera is open, the runtime can never drift away
 * from the installed package version, and it keeps working offline on a clinic
 * or school network.
 *
 * Because both are served `immutable` with a one year max-age, the paths have
 * to be content-addressed or a caller who cached the old bytes would keep them
 * for a year after an upgrade. So:
 *
 *   - the WASM runtime goes in public/mediapipe/wasm-<hash>/, generated here
 *     (~36 MB, gitignored) and regenerated on predev and prebuild
 *   - the model bundle is committed as public/models/face_landmarker.<hash>.task
 *     and this script verifies its name still matches its contents
 *
 * Both resolved paths are written into lib/vision/assetPaths.generated.ts,
 * which IS committed. Upgrading MediaPipe therefore produces a lockfile diff
 * and a path diff in the same commit, which is the point.
 */
import { createHash } from "node:crypto";
import { cp, mkdir, readdir, readFile, rm, stat, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import path from "node:path";

const require = createRequire(import.meta.url);
const root = process.cwd();

const HASH_LENGTH = 8;

function shortHash(buffers) {
  const hash = createHash("sha256");
  for (const buffer of buffers) hash.update(buffer);
  return hash.digest("hex").slice(0, HASH_LENGTH);
}

// ---------------------------------------------------------------- WASM runtime

const packageEntry = require.resolve("@mediapipe/tasks-vision");
const wasmSource = path.join(path.dirname(packageEntry), "wasm");

await stat(wasmSource).catch(() => {
  throw new Error(
    `Could not find MediaPipe WASM assets at ${wasmSource}. Run \`npm install\` first.`,
  );
});

const wasmFiles = (await readdir(wasmSource)).sort();
const wasmHash = shortHash(
  await Promise.all(
    wasmFiles.map(async (name) =>
      Buffer.concat([
        Buffer.from(name),
        await readFile(path.join(wasmSource, name)),
      ]),
    ),
  ),
);

const wasmDirName = `wasm-${wasmHash}`;
const mediapipeDir = path.join(root, "public", "mediapipe");
const wasmTarget = path.join(mediapipeDir, wasmDirName);

// Drop any previous hash directory so public/ does not accumulate 36 MB per
// MediaPipe upgrade.
await mkdir(mediapipeDir, { recursive: true });
for (const entry of await readdir(mediapipeDir)) {
  if (entry !== wasmDirName) {
    await rm(path.join(mediapipeDir, entry), { recursive: true, force: true });
  }
}

await cp(wasmSource, wasmTarget, { recursive: true });

// ---------------------------------------------------------------- model bundle

const modelsDir = path.join(root, "public", "models");
const modelFiles = (await readdir(modelsDir)).filter((name) =>
  name.endsWith(".task"),
);

if (modelFiles.length !== 1) {
  throw new Error(
    `Expected exactly one .task model in public/models, found ${modelFiles.length}: ${modelFiles.join(", ")}`,
  );
}

const modelFile = modelFiles[0];
const modelHash = shortHash([await readFile(path.join(modelsDir, modelFile))]);
const expectedModelFile = `face_landmarker.${modelHash}.task`;

if (modelFile !== expectedModelFile) {
  throw new Error(
    `Model filename does not match its contents.\n` +
      `  found:    public/models/${modelFile}\n` +
      `  expected: public/models/${expectedModelFile}\n` +
      `Rename it. The hash is in the filename so the file can be cached ` +
      `immutably, which only holds if the name tracks the bytes.`,
  );
}

// ------------------------------------------------------------ generated module

const generatedPath = path.join(root, "lib", "vision", "assetPaths.generated.ts");
const generated = `// GENERATED by scripts/sync-mediapipe-assets.mjs. Do not edit by hand.
//
// Both paths are content-addressed so they can be served immutable. Run
// \`npm run sync:assets\` after changing the MediaPipe version or the model
// bundle, and commit the result.

/** Directory FilesetResolver loads the WASM runtime from. */
export const WASM_BASE_PATH = "/mediapipe/${wasmDirName}";

/** Face Landmarker model bundle. */
export const MODEL_ASSET_PATH = "/models/${expectedModelFile}";
`;

const previous = await readFile(generatedPath, "utf8").catch(() => null);
if (previous !== generated) {
  await writeFile(generatedPath, generated);
  console.log(
    previous === null
      ? "[mediapipe] wrote lib/vision/assetPaths.generated.ts"
      : "[mediapipe] asset paths CHANGED, commit lib/vision/assetPaths.generated.ts",
  );
}

console.log(
  `[mediapipe] wasm -> public/mediapipe/${wasmDirName} (${wasmFiles.length} files)`,
);
console.log(`[mediapipe] model -> public/models/${expectedModelFile}`);
